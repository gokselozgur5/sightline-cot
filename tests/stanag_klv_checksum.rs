use sightline_cot::stanag4609::StanagTimestamp;

#[test]
fn klv_packet_ends_with_the_st0601_checksum() {
    let packet = StanagTimestamp::from_micros(1_700_000_000_000_000).to_klv_packet();
    let expected: [u8; 31] = [
        0x06, 0x0E, 0x2B, 0x34, 0x02, 0x0B, 0x01, 0x01, 0x0E, 0x01, 0x03, 0x01, 0x01, 0x00, 0x00,
        0x00, 0x0E, 0x02, 0x08, 0x00, 0x06, 0x0A, 0x24, 0x18, 0x1E, 0x40, 0x00, 0x01, 0x02, 0xA6,
        0xB5,
    ];
    assert_eq!(packet, expected);
}
