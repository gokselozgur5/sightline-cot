use sightline_cot::proto::decode_tak_packet;

const PACKET: [u8; 87] = [
    0xBF, 0x01, 0xBF, 0x12, 0x52, 0x0A, 0x05, 0x61, 0x2D, 0x66, 0x2D, 0x47, 0x2A, 0x02, 0x55, 0x31,
    0x30, 0x80, 0xBC, 0xC9, 0xB2, 0xC6, 0x33, 0x38, 0x80, 0xBC, 0xC9, 0xB2, 0xC6, 0x33, 0x40, 0xE0,
    0x90, 0xCD, 0xB2, 0xC6, 0x33, 0x4A, 0x03, 0x6D, 0x2D, 0x67, 0x51, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x40, 0x43, 0x40, 0x59, 0x00, 0x00, 0x00, 0x00, 0x00, 0x50, 0x53, 0xC0, 0x61, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x24, 0x40, 0x69, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x14, 0x40, 0x71, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x14, 0x40,
];

#[test]
fn reference_tak_protocol_v1_packet_decodes() {
    let evt = decode_tak_packet(&PACKET).expect("valid TAK Protocol v1 mesh packet");
    assert_eq!(evt.r#type, "a-f-G");
    assert_eq!(evt.uid, "U1");
    assert_eq!(evt.send_time, 1_771_243_200_000);
    assert_eq!(evt.how, "m-g");
    assert_eq!((evt.lat, evt.lon), (38.5, -77.25));
}
